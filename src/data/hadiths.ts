// دالة للبحث في الأحاديث
export const searchHadiths = (query: string): Hadith[] => {
  if (!query.trim()) return hadiths;
  
  const searchTerm = query.toLowerCase();
  return hadiths.filter(hadith => 
    hadith.arabicText.includes(query) ||
    hadith.translation.toLowerCase().includes(searchTerm) ||
    hadith.narrator.toLowerCase().includes(searchTerm) ||
    hadith.theme.toLowerCase().includes(searchTerm) ||
    hadith.collection.toLowerCase().includes(searchTerm) ||
    hadith.keywords.some(keyword => keyword.toLowerCase().includes(searchTerm))
  );
};

// دالة للحصول على الأحاديث حسب المجموعة
export const getHadithsByCollection = (collection: string): Hadith[] => {
  return hadiths.filter(hadith => hadith.collection === collection);
};

// دالة للحصول على جميع المجموعات
export const getCollections = (): string[] => {
  return [...new Set(hadiths.map(hadith => hadith.collection))];
};

// دالة للحصول على الأحاديث حسب الموضوع
export const getHadithsByTheme = (theme: string): Hadith[] => {
  return hadiths.filter(hadith => hadith.theme === theme);
};